#!/usr/bin/env node
// Regenerates docs/tools.md from the hosted server's tool list.
//
//   AI_SHOPPING_FEEDS_API_KEY=... npm run tools:update     # from the live server
//   npm run tools:update -- --from tools.json              # from a saved tools/list result
//
// Use a key with every scope, or the list only shows the tools that key can call.
import { readFileSync, writeFileSync } from 'node:fs';

import { Client, StreamableHTTPClientTransport } from '@modelcontextprotocol/client';

const GROUPS = {
  feeds: 'Feeds',
  products: 'Products',
  rules: 'Rules',
  ai: 'AI optimisation',
  classification: 'Listing quality',
  taxonomy: 'Google product categories',
  exports: 'Exports',
  channels: 'Channels',
  labels: 'Performance labels',
  creatives: 'Creatives (product ads)',
  brands: 'Brands',
  account: 'Account and billing',
  docs: 'Help docs'
};

async function fetchTools() {
  const apiKey = process.env.AI_SHOPPING_FEEDS_API_KEY;
  if (!apiKey) throw new Error('Set AI_SHOPPING_FEEDS_API_KEY or pass --from <file>.');
  const url = new URL(process.env.AI_SHOPPING_FEEDS_API_URL || 'https://app.aishoppingfeeds.com/api/v1/mcp');
  const client = new Client({ name: 'tools-doc', version: '0.0.0' }, { versionNegotiation: { mode: 'auto' } });
  await client.connect(new StreamableHTTPClientTransport(url, {
    requestInit: { headers: { Authorization: `Bearer ${apiKey}` } }
  }));
  // With no cursor, listTools follows nextCursor and returns every page.
  const { tools } = await client.listTools();
  await client.close();
  return tools;
}

function render(tools) {
  const byGroup = new Map();
  for (const tool of tools) {
    const group = tool.name.split('.')[0];
    if (!byGroup.has(group)) byGroup.set(group, []);
    byGroup.get(group).push(tool);
  }
  const order = [...Object.keys(GROUPS), ...[...byGroup.keys()].filter((g) => !(g in GROUPS)).sort()];
  const writes = tools.filter((tool) => tool.annotations?.readOnlyHint !== true).length;

  const lines = [
    '# Tools',
    '',
    `The server exposes ${tools.length} tools in ${byGroup.size} groups. ${tools.length - writes} only read data;`,
    `the other ${writes} change something and are hidden by \`--read-only\`. Most tools that change data`,
    'need `confirm: true`, so your agent should ask you first.',
    '',
    'Your agent only sees the tools your API key\'s scopes allow. Names use `_`, so `feeds.list` on the',
    'REST docs is `feeds_list` here. Use a group name with `--tools` to expose only that group.',
    '',
    '_Generated by `npm run tools:update`. Do not edit by hand._',
    ''
  ];
  for (const group of order) {
    const items = byGroup.get(group);
    if (!items) continue;
    lines.push(`## ${GROUPS[group] ?? group} (\`${group}\`)`, '', '| Tool | Access | What it does |', '| --- | --- | --- |');
    for (const tool of items) {
      const access = tool.annotations?.readOnlyHint === true ? 'Read' : 'Write';
      const description = (tool.description ?? '').replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
      lines.push(`| \`${tool.name.replace(/[^A-Za-z0-9_-]/g, '_')}\` | ${access} | ${description} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

const fromIndex = process.argv.indexOf('--from');
const tools = fromIndex > -1
  ? JSON.parse(readFileSync(process.argv[fromIndex + 1], 'utf8')).tools
  : await fetchTools();
writeFileSync(new URL('../docs/tools.md', import.meta.url), render(tools));
console.log(`docs/tools.md: ${tools.length} tools`);
